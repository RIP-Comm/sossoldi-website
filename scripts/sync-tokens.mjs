#!/usr/bin/env node
/**
 * Copy the single source of truth for the visual system into the site.
 * Fails loudly when the social kit moved, instead of silently shipping
 * another palette.
 *
 * Fonts: only Nunito Sans is copied, and each weight is subset to Latin and
 * converted to WOFF2 (~25 KB instead of ~150 KB) because the site is text.
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = path.resolve(import.meta.dirname, "..");
const candidates = [
  process.env.SOSSOLDI_TOKENS,
  path.resolve(root, "../sossoldi-social-kit/design/tokens.css"),
  "/Users/nomi/Projects/sossoldi-social-kit/design/tokens.css",
].filter(Boolean);

const target = path.join(root, "src/assets/css/tokens.css");
const source = candidates.find((file) => fs.existsSync(file));

// Cloudflare Pages builds from this repo alone: the social kit is a local
// folder, not a dependency of this repo, so in CI there is nothing to copy
// from. CI ships the committed tokens.css (generated on a Mac, reviewed in the
// diff); a local build keeps regenerating it from the kit and fails loudly
// when the kit moved.
if (!source && process.env.CI) {
  if (!fs.existsSync(target)) {
    console.error(
      "sync-tokens: CI build without a committed src/assets/css/tokens.css.\n" +
        "Run `npm run build` locally and commit the generated file.",
    );
    process.exit(1);
  }
  console.log("sync-tokens: no social kit in CI, using the committed tokens.css");
  process.exit(0);
}

if (!source) {
  console.error(
    "sync-tokens: tokens.css not found.\n" +
      "Expected at ../sossoldi-social-kit/design/tokens.css or in $SOSSOLDI_TOKENS.",
  );
  process.exit(1);
}

fs.mkdirSync(path.dirname(target), { recursive: true });

const sourceCss = fs.readFileSync(source, "utf8")
  // The CSS is copied to /assets/css/, fonts to /assets/fonts/.
  .replaceAll('url("fonts/', 'url("../fonts/')
  .replaceAll("url('fonts/", "url('../fonts/")
  // Fonts are shipped as subset WOFF2 (see below), never as raw TTF.
  .replaceAll(".ttf", ".woff2");

const banner =
  "/* GENERATED by scripts/sync-tokens.mjs — do not edit.\n" +
  `   Source: ${path.relative(root, source)}\n` +
  "   The palette lives in sossoldi-social-kit/design/tokens.json. */\n\n";

fs.writeFileSync(target, banner + sourceCss);

const fontSource = path.resolve(path.dirname(source), "fonts");
const fontTarget = path.join(root, "src/assets/fonts");
fs.mkdirSync(fontTarget, { recursive: true });

const unicodes = "U+0000-00FF,U+0100-017F,U+2000-206F,U+20AC,U+2122,U+2192,U+2190,U+2191,U+2193";

if (fs.existsSync(fontSource)) {
  for (const file of fs.readdirSync(fontSource)) {
    if (!file.startsWith("NunitoSans-") || !file.endsWith(".ttf")) continue;
    const input = path.join(fontSource, file);
    const output = path.join(fontTarget, file.replace(/\.ttf$/, ".woff2"));
    if (fs.existsSync(output) && fs.statSync(output).mtimeMs > fs.statSync(input).mtimeMs) continue;
    try {
      execFileSync(
        "python3",
        [
          "-m",
          "fontTools.subset",
          input,
          `--unicodes=${unicodes}`,
          "--layout-features=*",
          "--flavor=woff2",
          "--no-hinting",
          `--output-file=${output}`,
        ],
        { stdio: ["ignore", "ignore", "inherit"] },
      );
    } catch (error) {
      // Cloudflare Pages has no Python: keep the committed WOFF2 files.
      if (fs.existsSync(output)) {
        console.warn(`sync-tokens: could not rebuild ${path.basename(output)}, keeping the committed file`);
      } else {
        throw new Error(`sync-tokens: fontTools missing and ${output} does not exist`);
      }
    }
  }
}

console.log(`tokens: ${path.relative(root, target)} ← ${source}`);
