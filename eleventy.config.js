import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import MarkdownIt from "markdown-it";
import markdownItAnchor from "markdown-it-anchor";
import pluginRss from "@11ty/eleventy-plugin-rss";

/** Slug used for heading ids and file names. */
function slugify(value) {
  return String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

/** Strip the leading language segment and return the locale-aware URL. */
function localize(stem, lang) {
  let url = String(stem || "/").replace(/^\/(en|it)(?=\/|$)/, "");
  if (url === "" || url === "/index") url = "/";
  if (url.endsWith("/index")) url = url.slice(0, -"/index".length) + "/";
  if (!url.endsWith("/") && !url.includes(".")) url += "/";
  return lang === "it" ? (url === "/" ? "/it/" : `/it${url}`) : url;
}

export default function (eleventyConfig) {
  eleventyConfig.addPlugin(pluginRss);

  eleventyConfig.amendLibrary("md", (md) =>
    md.use(markdownItAnchor, {
      level: [2, 3],
      slugify,
      permalink: markdownItAnchor.permalink.linkInsideHeader({
        symbol: "#",
        class: "heading-anchor",
        placement: "after",
        ariaHidden: false,
      }),
    }),
  );

  eleventyConfig.addPassthroughCopy({ "src/assets": "assets" });
  eleventyConfig.addPassthroughCopy({ "src/robots.txt": "robots.txt" });
  eleventyConfig.addPassthroughCopy({ "src/_headers": "_headers" });

  // The token file is generated by scripts/sync-tokens.mjs; do not copy a stale one.
  eleventyConfig.ignores.add("src/assets/css/tokens.css");

  eleventyConfig.addFilter("localeUrl", localize);

  eleventyConfig.addFilter("altUrl", (url, lang) => {
    const clean = String(url || "/");
    if (lang === "it") {
      const stripped = clean.replace(/^\/it(?=\/|$)/, "");
      return stripped === "" ? "/" : stripped;
    }
    return clean === "/" ? "/it/" : `/it${clean}`;
  });

  eleventyConfig.addFilter("absoluteUrl", (url, base) => {
    if (!url) return base;
    if (/^https?:\/\//.test(url)) return url;
    return `${String(base).replace(/\/$/, "")}/${String(url).replace(/^\//, "")}`;
  });

  eleventyConfig.addFilter("dateLabel", (value, lang) => {
    if (!value) return "";
    const date = value instanceof Date ? value : new Date(value);
    if (Number.isNaN(date.getTime())) return "";
    return new Intl.DateTimeFormat(lang === "it" ? "it-IT" : "en-GB", {
      day: "numeric",
      month: "long",
      year: "numeric",
      timeZone: "UTC",
    }).format(date);
  });

  eleventyConfig.addFilter("enPath", (url) => {
    const clean = String(url || "/").replace(/^\/it(?=\/|$)/, "");
    return clean === "" ? "/" : clean;
  });

  eleventyConfig.addFilter("itPath", (url) => {
    const clean = String(url || "/");
    if (clean.startsWith("/it/") || clean === "/it") return clean === "/it" ? "/it/" : clean;
    return clean === "/" ? "/it/" : `/it${clean}`;
  });

  eleventyConfig.addFilter("dateIso", (value) => {
    if (!value) return "";
    const date = value instanceof Date ? value : new Date(value);
    return Number.isNaN(date.getTime()) ? "" : date.toISOString();
  });

  eleventyConfig.addFilter("readingTime", (content, lang) => {
    const words = String(content || "")
      .replace(/<[^>]*>/g, " ")
      .split(/\s+/)
      .filter(Boolean).length;
    const minutes = Math.max(1, Math.round(words / 200));
    return lang === "it" ? `${minutes} min di lettura` : `${minutes} min read`;
  });

  eleventyConfig.addFilter("toc", (content) => {
    const headings = [];
    const re = /<h([23])\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/g;
    let match;
    while ((match = re.exec(String(content || ""))) !== null) {
      headings.push({
        level: Number(match[1]),
        id: match[2],
        text: match[3]
          .replace(/<a[^>]*class="heading-anchor"[^>]*>[\s\S]*?<\/a>/g, "")
          .replace(/<[^>]*>/g, "")
          .replace(/&amp;/g, "&")
          .replace(/&#39;/g, "'")
          .trim(),
      });
    }
    return headings;
  });

  eleventyConfig.addFilter("excerpt", (content, length = 180) => {
    const text = String(content || "")
      .replace(/<[^>]*>/g, " ")
      .replace(/\s+/g, " ")
      .trim();
    return text.length > length ? `${text.slice(0, length).trimEnd()}…` : text;
  });

  eleventyConfig.addFilter("number", (value, lang) =>
    new Intl.NumberFormat(lang === "it" ? "it-IT" : "en-GB").format(Number(value) || 0),
  );

  eleventyConfig.addFilter("sha256", (value) =>
    crypto.createHash("sha256").update(String(value)).digest("hex"),
  );

  eleventyConfig.addFilter("json", (value) => JSON.stringify(value));

  eleventyConfig.addFilter("contains", (haystack, needle) =>
    String(haystack || "").includes(needle),
  );

  eleventyConfig.addFilter("markdown", (value) => {
    const md = new MarkdownIt({ html: true, linkify: true, typographer: false });
    return md.render(String(value || ""));
  });

  eleventyConfig.addFilter("docNeighbors", (docs, url) => {
    const index = docs.findIndex((item) => item.url === url);
    return {
      prev: index > 0 ? docs[index - 1] : null,
      next: index >= 0 && index + 1 < docs.length ? docs[index + 1] : null,
    };
  });

  eleventyConfig.addFilter(
    "docTitle",
    (docs, navId) => docs.find((item) => item.data.navId === navId)?.data.title || "",
  );

  eleventyConfig.addFilter("whereParent", (items, navId) =>
    items.filter((item) => item.data.parent === navId),
  );

  eleventyConfig.addFilter("split", (value, separator) => String(value).split(separator));

  eleventyConfig.addCollection("docs_en", (collection) =>
    collection
      .getFilteredByGlob("src/en/docs/**/*.md")
      .filter((item) => !item.data.draft)
      .sort((a, b) => (a.data.order ?? 99) - (b.data.order ?? 99)),
  );

  eleventyConfig.addCollection("docs_it", (collection) =>
    collection
      .getFilteredByGlob("src/it/docs/**/*.md")
      .filter((item) => !item.data.draft)
      .sort((a, b) => (a.data.order ?? 99) - (b.data.order ?? 99)),
  );

  eleventyConfig.addCollection("posts_en", (collection) =>
    collection
      .getFilteredByGlob("src/en/blog/**/*.md")
      .filter((item) => !item.data.draft)
      .sort((a, b) => new Date(b.data.date) - new Date(a.data.date)),
  );

  eleventyConfig.addCollection("posts_it", (collection) =>
    collection
      .getFilteredByGlob("src/it/blog/**/*.md")
      .filter((item) => !item.data.draft)
      .sort((a, b) => new Date(b.data.date) - new Date(a.data.date)),
  );

  eleventyConfig.addCollection("allPages", (collection) =>
    collection.getAll().filter((item) => item.url && item.outputPath?.endsWith(".html")),
  );

  eleventyConfig.addShortcode("year", () => String(new Date().getFullYear()));

  // Fail loudly when a translation guard would be silently bypassed.
  eleventyConfig.on("eleventy.after", () => {
    const required = ["src/assets/css/tokens.css"];
    for (const file of required) {
      if (!fs.existsSync(path.join(process.cwd(), file))) {
        throw new Error(`Missing generated file ${file} — run npm run tokens first.`);
      }
    }
  });

  return {
    dir: {
      input: "src",
      output: "_site",
      includes: "_includes",
      layouts: "_includes/layouts",
      data: "_data",
    },
    templateFormats: ["md", "njk", "11ty.js"],
    markdownTemplateEngine: "njk",
    htmlTemplateEngine: "njk",
    dataTemplateEngine: "njk",
  };
}
